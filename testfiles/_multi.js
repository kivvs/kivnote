// 示例：用于验证语法高亮与行号
const fs = require('fs');

function readConfig(path) {
    // 读取并返回配置
    const text = fs.readFileSync(path, 'utf8');
    if (!text) {
        return null;
    }
    let cfg = JSON.parse(text);
    const maxRows = 2000;
    for (let i = 0; i < 10; i++) {
        console.log("row " + i + " -> " + maxRows);
    }
    return cfg;
}

module.exports = { readConfig };
